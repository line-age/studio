// Writes src/styles/tokens.css from tokens/figma-tokens.json.
// Every Figma variable becomes one CSS variable named exactly as its Figma
// web code syntax, so a value can be traced both ways by name.
import { writeFileSync } from "node:fs"
import {
  FAMILIES,
  TOKENS_CSS,
  WEIGHTS,
  cssValue,
  isThemeKey,
  readTokens,
  shadowName,
  shadowValue,
} from "./tokens-lib.mjs"

const tokens = readTokens()
const vars = tokens.variables
const colors = vars.filter((v) => v.type === "COLOR")
const numbers = vars.filter((v) => v.type !== "COLOR" && !isThemeKey(v))
const themeKeys = vars.filter(isThemeKey)

const decl = (name, value) => `  ${name}: ${value};`
const lines = []

lines.push(
  "/*",
  " * GENERATED by scripts/build-tokens.mjs from tokens/figma-tokens.json.",
  ` * Figma file ${tokens.source.figmaFileKey}, read ${tokens.source.readAt}.`,
  " * Do not edit. Change the variable in Figma, re-read it, then run",
  " * `pnpm tokens:build`. `pnpm tokens:check` fails if this file drifts.",
  " */",
  ""
)

lines.push(
  "/* Figma variables: Color and Scale. One light theme. */",
  ":root {"
)
let group = ""
for (const v of [...colors, ...numbers]) {
  const g = `${v.collection}: ${v.name.includes("/") ? v.name.split("/")[0] : "base"}`
  if (g !== group) {
    if (group) lines.push("")
    lines.push(`  /* ${g} */`)
    group = g
  }
  lines.push(decl(v.css, cssValue(v)))
}
lines.push("}", "")

lines.push(
  "/* Figma names that are also Tailwind theme keys, plus the shadow styles. */",
  "@theme static {"
)
for (const v of themeKeys) lines.push(decl(v.css, cssValue(v)))
lines.push("")
for (const e of tokens.effects) lines.push(decl(shadowName(e), shadowValue(e)))
lines.push("}", "")

lines.push(
  "/* Tailwind utilities for the variables above: bg-primary, text-state-ai,",
  "   h-control, w-panel-left and so on. */",
  "@theme inline {",
  decl("--font-sans", '"Inter Variable", ui-sans-serif, system-ui, sans-serif'),
  decl("--font-mono", '"JetBrains Mono Variable", ui-monospace, monospace'),
  ""
)
for (const v of colors) {
  lines.push(decl(`--color-${v.css.slice(2)}`, `var(${v.css})`))
}
lines.push("")
for (const v of numbers) {
  const m = v.css.match(/^--(size|layout)-(.+)$/)
  if (m) lines.push(decl(`--spacing-${m[2]}`, `var(${v.css})`))
}
lines.push("}", "")

lines.push(
  "/* Figma text styles ui/*. Use these, not text-sm plus font-medium. Named type-* and not text-*, because cn() would merge text-* with a text colour and drop one. */"
)
for (const s of tokens.textStyles) {
  const family = FAMILIES[s.family]
  const weight = WEIGHTS[s.style]
  if (!family || !weight) {
    throw new Error(`Text style ${s.name}: unknown family or weight`)
  }
  lines.push(
    `@utility type-${s.name.replace("/", "-")} {`,
    decl("font-family", family),
    decl("font-size", `${s.size}px`),
    decl("line-height", `${s.lineHeight}px`),
    decl("font-weight", weight),
    "}"
  )
}

writeFileSync(TOKENS_CSS, lines.join("\n") + "\n")
console.log(
  `tokens.css: ${vars.length} variables, ${tokens.textStyles.length} text styles, ${tokens.effects.length} shadows`
)
